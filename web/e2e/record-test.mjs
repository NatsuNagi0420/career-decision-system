import { chromium } from 'playwright';
const token = process.env.DEMO_TOKEN;
const dir = 'D:/Project/career-decision-system/video/raw/clips';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir, size: { width: 1920, height: 1080 } } });
const page = await context.newPage();
await page.addInitScript(t => { localStorage.setItem('career.session.token', t); localStorage.setItem('suinai.onboarding.v1.local.3','completed'); }, token);
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(5000);
await page.evaluate(() => {
  const c = document.createElement('div');
  c.id = '__fake_cursor';
  c.style.cssText = 'position:fixed;left:960px;top:540px;width:18px;height:18px;border-radius:50%;background:rgba(255,255,255,.9);border:2px solid rgba(40,35,60,.75);box-shadow:0 1px 6px rgba(0,0,0,.35);z-index:2147483647;pointer-events:none;transform:translate(-9px,-9px);transition:transform .08s linear;';
  document.body.appendChild(c);
  window.addEventListener('mousemove', e => { c.style.left = e.clientX + 'px'; c.style.top = e.clientY + 'px'; });
  window.addEventListener('mousedown', () => { c.style.background='rgba(120,90,200,.95)'; c.style.transform='translate(-9px,-9px) scale(.72)'; });
  window.addEventListener('mouseup', () => { c.style.background='rgba(255,255,255,.9)'; c.style.transform='translate(-9px,-9px) scale(1)'; });
});
await page.mouse.move(500, 500, { steps: 20 });
await page.waitForTimeout(1000);
await page.getByText('职业工作台', { exact: false }).first().click();
await page.waitForTimeout(2000);
await page.mouse.move(900, 500, { steps: 15 });
await page.waitForTimeout(1000);
const video = page.video();
await context.close();
await browser.close();
const path = await video.path();
