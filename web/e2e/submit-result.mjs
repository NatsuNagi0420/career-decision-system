import { chromium } from 'playwright';
const token = process.env.DEMO_TOKEN;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.addInitScript(t => { localStorage.setItem('career.session.token', t); localStorage.setItem('suinai.onboarding.v1.local.3','completed'); }, token);
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(4500);
await page.getByText('职业工作台', { exact: false }).first().click();
await page.waitForTimeout(1200);
await page.getByRole('tab', { name: '成长行动' }).click();
await page.waitForTimeout(1200);
await page.getByText('提交我的行动结果').click();
await page.waitForTimeout(500);
const ta = page.locator('.workbench-action-result textarea').first();
await ta.fill('我重写了二手平台项目，拆成 3 条可核对的后端成果：商品发布接口补充草稿与图片处理；搜索接口加入 Redis 缓存；订单接口补充幂等键和超时重试。仓库链接和压测记录已整理到项目文档。');
await page.getByRole('button',{name:'提交结果并标记完成'}).click();
await page.waitForTimeout(2000);
console.log('TEXT TAIL', (await page.locator('body').innerText()).slice(-1500));
await page.screenshot({ path: 'D:\\Project\\career-decision-system\\video\\raw\\web-action-done.png', fullPage: false });
await browser.close();
